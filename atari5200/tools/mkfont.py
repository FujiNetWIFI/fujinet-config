#!/usr/bin/env python3
"""mkfont.py -- CONFIG's ANTIC mode 2 font (antic.h's mt_font) from font.txt.

font.txt is the NES CONFIG's format: "= c" or "= $hh [plane N]" headers,
then up to 8 rows of '#' (ink, in any plane) and '.' (paper). Tile numbers
are ASCII, with the frame, cursor and bar tiles below $20. Mode 2 has one
colour, so every plane's ink is a set bit. The output is 128 characters of
8 bytes, top row first, in ANTIC's internal-code order: codes $00-$3F are
tiles $20-$5F, $40-$5F are tiles $00-$1F, $60-$7F are tiles $60-$7F.

    mkfont.py font.txt out.inc
"""

import sys


def parse(path):
    tiles = {}
    cur = None
    for lineno, raw in enumerate(open(path, encoding="ascii"), 1):
        line = raw.rstrip("\n")
        if line == "" or line == "#" or line.startswith("# "):
            cur = None
            continue
        if line.startswith("= "):
            words = line[2:].split()
            name = line[2:3] if len(line) == 3 else words[0]
            code = ord(name) if len(name) == 1 else int(name[1:], 16)
            if not 0 <= code < 128:
                sys.exit("%s:%d: tile $%02X out of range" % (path, lineno, code))
            cur = tiles[code] = [0] * 8
            row = 0
            continue
        if cur is None or len(line) > 8 or set(line) - set("#.") or row == 8:
            sys.exit("%s:%d: bad glyph row %r" % (path, lineno, line))
        cur[row] = sum(0x80 >> x for x, ch in enumerate(line) if ch == "#")
        row += 1
    return tiles


def tile_of(code):
    if code < 0x40:
        return code + 0x20
    if code < 0x60:
        return code - 0x40
    return code


def main():
    tiles = parse(sys.argv[1])
    with open(sys.argv[2], "w") as out:
        out.write("; GENERATED by tools/mkfont.py from %s -- do not edit.\n" % sys.argv[1])
        for code in range(128):
            rows = tiles.get(tile_of(code), [0] * 8)
            out.write("        .byte " + ",".join("$%02X" % b for b in rows)
                      + "   ; $%02X\n" % code)


if __name__ == "__main__":
    main()
