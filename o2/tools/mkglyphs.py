HALF = 32                          # 32 x 7 = 224 bytes a page


def rows(c):
    out = []
    for line in FONT[c]:
        v = 0
        for x, ch in enumerate(line):
            if ch == "#":
                v |= 1 << (x + 1)        # one pixel in from the left
        out.append(v)
    return out


def main(out):
    keys = sorted(FONT)
    tab = []
    for code in range(0x20, 0x80):
        c = chr(code)
        tab.append(keys.index(c) if c in FONT else 0xFF)
    lines = ["; GENERATED by tools/mkglyphs.py -- do not edit.",
             "; gtab: code - $20 -> the glyph's number (0FFh: the font has it);",
             "; glyphs: 7 rows each, bit 0 the leftmost pixel.",
             "gtab:"]
    for i in range(0, 96, 16):
        lines.append("    db " + ", ".join("%03Xh" % v for v in tab[i:i + 16]))
    lines.append("NGLYPHS equ %d" % len(keys))
    lines.append("GLYPHA equ %d                ; glyphsa holds the first GLYPHA" % HALF)
    open(out, "w").write("\n".join(lines) + "\n")
    # two 256-byte pages' worth: MOVP reads its own page only
    for name, part in (("a", keys[:HALF]), ("b", keys[HALF:])):
        body = ["    db " + ", ".join("%03Xh" % v for v in rows(c)) + "  ; " + repr(c) for c in part]
        open(out.replace("glyphs.inc", "glyphs%s.inc" % name), "w").write(
            "; GENERATED by tools/mkglyphs.py -- do not edit.\nglyphs%s:\n" % name
            + "\n".join(body) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
