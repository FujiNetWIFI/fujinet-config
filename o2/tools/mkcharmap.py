#!/usr/bin/env python3
"""mkcharmap.py -- ASCII to the 8244's character generator: build/charmap.inc.

    mkcharmap.py OUT

charmap: codes $20-$7F, one byte each: the glyph (bits 0-5) and its class
(bits 6-7), which disp.inc's gptr turns into a colour:
    0  the font has it                      the line's colour
    1  lower case: the upper-case glyph     LCCOL
    2  not in the font: a look-alike        SUBCOL
The font (o2doc appendix C) has upper case, digits and
    : $ ? + - . = / and x (*), divide (%), backslash
and nothing else. Codes $00-$1F are glyph code+32 (gptr): the pictures and
the font's upper half, "AZXCVBM.-*%=YN/#", then "10", the ball ...
"""
import sys

ROM = "0123456789:$ ?LP+WERTUIOQSDFGHJKAZXCVBM.-*%=YN/#"
G_TEN, G_BACKSLASH, G_BLOCK = 48, 59, 47
G_TIMES, G_DIVIDE = ROM.index("*"), ROM.index("%")
# What a character the font lacks is drawn as (the editor's magnifier shows
# the real one): the nearest shape the 64 glyphs have.
LOOKALIKE = {
    "!": "I", '"': ":", "#": G_BLOCK, "%": G_DIVIDE, "&": "+", "'": ".",
    "(": "C", ")": "J", "*": G_TIMES, ",": ".", ";": ":", "<": "C",
    ">": "J", "@": "A", "[": "C", "]": "J", "^": "A", "_": "-", "`": ".",
    "{": "C", "|": "I", "}": "J", "~": "-",
}


def glyph_of(c):
    if c in ROM and c not in "*%#":
        return ROM.index(c), 0
    if c == "\\":
        return G_BACKSLASH, 0
    if c.islower():
        return ROM.index(c.upper()), 1
    if c in LOOKALIKE:
        g = LOOKALIKE[c]
        return (ROM.index(g) if isinstance(g, str) else g), 2
    return ROM.index(" "), 2       # DEL: a blank


def main(out):
    vals = []
    for code in range(0x20, 0x80):
        g, cls = glyph_of(chr(code))
        vals.append(g | cls << 6)
    rows = [", ".join("%3d" % v for v in vals[i:i + 16]) for i in range(0, 96, 16)]
    open(out, "w").write(
        "; GENERATED by tools/mkcharmap.py -- do not edit.\n"
        "; code $20-$7F -> 8244 glyph | class << 6 (0 font, 1 lower, 2 look-alike)\n"
        "charmap:\n" + "".join("    db %s\n" % r for r in rows))


if __name__ == "__main__":
    main(sys.argv[1])
