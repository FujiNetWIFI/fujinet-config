#!/bin/bash
# build.sh -- the Odyssey 2 CONFIG: build/config.bin, a protocol 2 (APPBANK)
# image -- the fixed half ($400-$7FF) and NPAGES pages of 2K.
#
#   ./build.sh                          the image
#   SPIKE=1 ./build.sh                  the engine's test pattern
#   WIFIFAKE=1 ./build.sh               WiFi set-up even when connected (tests)
#   LOBBY_HOST=... LOBBY_PATH=...       the lobby (ec.tnfs.io, /o2/lobby.bin)
#   PADN= LEAD= Y_ROW0= X_ROWTXT=       the layout and timing (src/equ.inc)
#
# Needs Macroassembler AS (~/asl/asl and p2bin, or ASL=/P2BIN=).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="${OUT:-$HERE/build}"
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
SPIKE="${SPIKE:-0}"
WIFIFAKE="${WIFIFAKE:-0}"
MAXPAGES=15                     # the firmware holds 1K + 15 x 2K
if [ "$SPIKE" = 1 ]; then NPAGES=2; else NPAGES="${NPAGES:-12}"; fi
mkdir -p "$OUT"

python3 "$HERE/tools/checkflags.py" "$HERE"/src/*.inc
python3 "$HERE/tools/mkcharmap.py" "$OUT/charmap.inc"
python3 "$HERE/tools/mkglyphs.py" "$OUT/glyphs.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'lob_host: db "%s",0\n' "${LOBBY_HOST:-ec.tnfs.io}"
  printf 'lob_path: db "%s",0\n' "${LOBBY_PATH:-/o2/lobby.bin}"
} > "$OUT/lobby.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  echo "SPIKE equ $SPIKE"
  echo "WIFIFAKE equ $WIFIFAKE"
  for v in SPKNOIN PADN GRIDNOPP LEAD Y_ROW0 Y_T0 Y_T1 X_ROWTXT GRIDNOP; do
    [ -n "${!v:-}" ] && echo "$v equ ${!v}"
  done
  true
} > "$OUT/flags.inc"
cp "$HERE"/src/*.inc "$HERE/g7000.h" "$HERE/config.a48" "$OUT/"

[ "$NPAGES" -le "$MAXPAGES" ] || { echo "build.sh: $NPAGES pages, over $MAXPAGES" >&2; exit 1; }
parts=""
for p in $(seq 0 $((NPAGES-1))); do
  printf '; GENERATED by build.sh -- do not edit.\nPAGE equ %d\nNPAGES equ %d\n    include "config.a48"\n' \
    "$p" "$NPAGES" > "$OUT/config_p$p.a48"
  ( cd "$OUT" && "$ASL" -q -L -U "config_p$p.a48" \
      && "$P2BIN" "config_p$p.p" "config_pg$p.bin" -r 0x800-0xFFF -l 0 >/dev/null \
      && "$P2BIN" "config_p$p.p" "config_fx$p.bin" -r 0x400-0x7FF -l 0 >/dev/null )
  python3 "$HERE/tools/checkobj.py" "$OUT/config_p$p.p"
  python3 "$HERE/tools/checklayout.py" "$OUT/config_p$p.lst"
  python3 "$HERE/tools/checkmb.py" "$OUT/config_p$p.lst" >/dev/null
  python3 "$HERE/tools/checkpage.py" "$OUT/config_p$p.lst"
  # Every page carries the fixed half; they have to be the same bytes.
  cmp -s "$OUT/config_fx0.bin" "$OUT/config_fx$p.bin" \
    || { echo "build.sh: page $p assembled a different fixed half" >&2; exit 1; }
  parts="$parts $OUT/config_pg$p.bin"
done
# The stack is 8 levels and wraps silently: interrupts plus the deepest main
# chain have to fit. Every page's entries are counted from 0: they are
# entered by far_go, a jump.
# Only the libraries (pages 1 and 10) are farcalled; the screens hand over
# by far_go.
python3 "$HERE/tools/checkstack.py" --far 1,10 $(for p in $(seq 0 $((NPAGES-1))); do echo "$OUT/config_p$p.lst"; done) >/dev/null
cat "$OUT/config_fx0.bin" $parts > "$OUT/config.bin"
size=$(wc -c < "$OUT/config.bin")
[ "$size" -eq $((1024 + 2048 * NPAGES)) ] \
  || { echo "build.sh: config.bin is $size bytes" >&2; exit 1; }
echo "${OUT#$HERE/}/config.bin: $size bytes, $NPAGES pages"
if [ "$SPIKE" = 1 ]; then echo "  (the SPIKE test pattern)"; fi
