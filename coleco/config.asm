; config.asm -- FujiNet CONFIG for the ColecoVision.
;
; WiFi setup, the 8 host slots, a file browser with filter, host-to-host
; copy, adapter info, the game lobby, and mount-and-boot with a progress
; window, in the Phantasy Star style of the Master System CONFIG (../sms on
; branch sms-phantasy-star), which this transcribes screen for screen.
;
; Bare metal: no OS7 calls and no NMI. VDP register 1 keeps its interrupt
; enable clear and the frame flag is polled (input.inc), so nothing ever
; lands between a VDP address write and its data, or inside a mailbox
; transaction. The console has 1K of RAM, so lists, host slots and the
; adapter config are drawn straight out of the cart's 1K reply window at
; F800H and streamed straight back into the next payload; path and src_spec
; are the only reply-to-RAM copies.
;
; Unless a routine says otherwise it may change AF, BC, DE and HL. IX
; belongs to the sound sequencer; IY is unused.

        INCLUDE "flags.inc"             ; generated by build.sh

; ---- states -------------------------------------------------------------
STATE_CHECK_WIFI   EQU     0
STATE_SET_WIFI     EQU     1
STATE_CONNECT EQU     2
STATE_HOSTS        EQU     3
STATE_FILES        EQU     4
STATE_INFO         EQU     5
STATE_LOBBY        EQU     6

; ---- geometry and limits --------------------------------------------------
HOST_SLOTS      EQU     8
HOST_STRIDE     EQU     32              ; READ_HOST_SLOTS: 8 x 32 bytes
LIST_TOP        EQU     2               ; lists sit on rows 2, 4, ... 16
LIST_ROWS       EQU     8
NAMELEN         EQU     30              ; listing width: columns 1-30
CUT_LEN         EQU     NAMELEN-2       ; a listed name this long may be cut
FULLLEN         EQU     120             ; re-read width for a full path
TITLE_MAX       EQU     26              ; fits in the main window's border
DEVICE_SLOT     EQU     0               ; the cartridge is the one device
MODE_READ       EQU     1
PATH_MAX        EQU     96              ; path and src_spec, NUL included
WIFI_MAX        EQU     15              ; networks listed; OTHER follows
SSID_LEN        EQU     33
PASS_MAX        EQU     63
FILTER_MAX      EQU     30
ENTRY_MAX       EQU     64              ; fn_entry, NUL included

; GET_ADAPTERCONFIG_EXTENDED field offsets (fujiDevice.h)
ACX_SSID        EQU     0
ACX_HOSTNAME    EQU     33
ACX_VERSION     EQU     125
ACX_LOCALIP     EQU     140
ACX_GATEWAY     EQU     156
ACX_NETMASK     EQU     172
ACX_DNSIP       EQU     188
ACX_MAC         EQU     204
ACX_BSSID       EQU     222

; ---- RAM: 7000H-73FFH, the stack at the top ----------------------------
; Never 7800H-7FFFH: without A15 on the cart edge those addresses reach
; the mailbox's hotspots. emu/drive.lua reads the first three bytes.
cb_active       EQU     7000H           ; the blinking cursor is live
cb_row          EQU     cb_active+1
state           EQU     cb_row+1
cb_col          EQU     state+1
cb_on           EQU     cb_col+1        ; its two tiles
cb_off          EQU     cb_on+1
cb_phase        EQU     cb_off+1
frames          EQU     cb_phase+1      ; frame flags seen; wraps
in_pad          EQU     frames+1        ; pad bits as last taken
in_key          EQU     in_pad+1        ; keypad code as last taken
in_cpad         EQU     in_key+1        ; the last sample, until it repeats
in_ckey         EQU     in_cpad+1
in_pend         EQU     in_ckey+1       ; new pad presses not yet read
in_pkey         EQU     in_pend+1       ; a new key's event, not yet read
in_held         EQU     in_pkey+1       ; frames at the last new press
in_rpt          EQU     in_held+1       ; directions auto-repeat
ovl_x0          EQU     in_rpt+1        ; the open pop-up
ovl_y0          EQU     ovl_x0+1
ovl_x1          EQU     ovl_y0+1
ovl_y1          EQU     ovl_x1+1
wb_x0           EQU     ovl_y1+1        ; win_box's working copy
wb_y0           EQU     wb_x0+1
wb_x1           EQU     wb_y0+1
wb_y1           EQU     wb_x1+1
wb_y            EQU     wb_y1+1
wb_wipe         EQU     wb_y+1
layout_up       EQU     wb_wipe+1
host            EQU     layout_up+1     ; the mounted/browsed host slot
src_host        EQU     host+1          ; copy: the source's host slot
copy_mode       EQU     src_host+1      ; nonzero while a copy is marked
cur             EQU     copy_mode+1     ; selected row on the page
nrows           EQU     cur+1           ; rows the page has
at_end          EQU     nrows+1         ; the page ends the directory
top             EQU     at_end+1        ; 2: first entry on the page
hosts_mask      EQU     top+2           ; bit i: slot i has a name
nnets           EQU     hosts_mask+1    ; networks the scan found
wtop            EQU     nnets+1         ; first network on the page: 0 or 8
long_rows       EQU     wtop+1          ; bit i: row i's name may be cut
sc_phase        EQU     long_rows+1     ; the name scroll
sc_frame        EQU     sc_phase+1
sc_wait         EQU     sc_frame+1
sc_len          EQU     sc_wait+1
sc_off          EQU     sc_len+1
sc_dir          EQU     sc_off+1
ed_len          EQU     sc_dir+1        ; the keyboard
ed_max          EQU     ed_len+1
ed_case         EQU     ed_max+1
ed_x            EQU     ed_case+1
ed_y            EQU     ed_x+1
mn_names        EQU     ed_y+1          ; 2: menu_pick
mn_events       EQU     mn_names+2      ; 2
mn_count        EQU     mn_events+2
mn_index        EQU     mn_count+1
mn_x0           EQU     mn_index+1
bt_want         EQU     mn_x0+1         ; the mount: SEQ awaited
bt_acked        EQU     bt_want+1
bt_last_st      EQU     bt_acked+1
bt_last_pct     EQU     bt_last_st+1
bt_idle         EQU     bt_last_pct+1
bt_quiet        EQU     bt_idle+1       ; 2
bt_frame        EQU     bt_quiet+2
bt_shown_px     EQU     bt_frame+1
bt_want_px      EQU     bt_shown_px+1
bt_shown_pct    EQU     bt_want_px+1
bt_want_pct     EQU     bt_shown_pct+1
bt_hi           EQU     bt_want_pct+1   ; apply: the bar's far edge
fade_level      EQU     bt_hi+1
snd_slaved      EQU     fade_level+1    ; T2 is following T1
snd_def         EQU     snd_slaved+1    ; 2: snd_play's own scratch
snd_vol         EQU     snd_def+2
cw_slot         EQU     snd_vol+1       ; cmd_write_host's own
cw_name         EQU     cw_slot+1       ; 2
tmp_a           EQU     cw_name+2       ; screen scratch: no library
                                        ; routine touches these
tmp_b           EQU     tmp_a+1
tmp_w           EQU     tmp_b+1         ; 2
numbuf          EQU     tmp_w+2         ; 6: decimal digits
voices          EQU     numbuf+6        ; 4 x VOICE_SIZE
rowbuf          EQU     voices+4*14     ; 32: VRAM-to-VRAM copies
path            EQU     rowbuf+32       ; current dir, '/' first and last
src_spec        EQU     path+PATH_MAX   ; copy source; the SSID; the stub
fn_entry        EQU     src_spec+PATH_MAX ; the keyboard's buffer; the filter
RAM_END         EQU     fn_entry+ENTRY_MAX
STACK_TOP       EQU     7400H
STACK_ROOM      EQU     160             ; 38 measured at the deepest

        IF      RAM_END+STACK_ROOM > STACK_TOP
        DB      ram_ledger_overflows_the_stack
        ENDIF

; ---- cartridge header --------------------------------------------------
; 55 AA skips the BIOS title screen, so start silences the sound chip and
; sets every VDP register itself. The OS7 table pointers are unused.
        ORG     8000H
        DB      55H,0AAH
        DW      0,0,0,0
        DW      start
        JP      rst_ret                 ; 800CH-801EH: RST 08H-38H
        JP      rst_ret
        JP      rst_ret
        JP      rst_ret
        JP      rst_ret
        JP      rst_ret
        JP      rst_ret
        JP      nmi                     ; 8021H

; The VDP interrupt stays disabled, so this runs only if a reset left it
; on; reading the status register drops the request.
nmi:    PUSH    AF
        IN      A,(VDP_CTRL)
        POP     AF
        RETN
rst_ret:
        RET

start:  DI
        LD      SP,STACK_TOP
        LD      A,80H                   ; 16K, display off, interrupt off
        LD      B,1
        CALL    vdp_reg
        IN      A,(VDP_CTRL)
        CALL    snd_init                ; the PSG powers up sounding
        LD      HL,cb_active            ; RESET re-enters with old values
        LD      DE,cb_active+1
        LD      BC,RAM_END-cb_active-1
        LD      (HL),0
        LDIR
        LD      A,1
        LD      (in_rpt),A
        CALL    snd_init
        CALL    in_init
        CALL    disp_init
        CALL    splash_show
        CALL    in_init                 ; drop presses made during the fade
        CALL    disp_init
        CALL    FNCHECK
        JR      Z,main_loop
        LD      HL,str_fujinet
        CALL    draw_frame
        LD      A,SND_ERROR
        CALL    snd_play
        LD      HL,str_no_cart
        CALL    status_line
no_cart_loop:
        CALL    in_frames               ; the buzz plays out
        JR      no_cart_loop

; ---- the state dispatcher ----------------------------------------------
; Each screen draws itself, runs its own event loop and returns once it
; has set `state` to something else.
main_loop:
        LD      HL,main_loop
        PUSH    HL
        LD      A,(state)
        CP      STATE_LOBBY+1
        JR      C,ml_ok
        LD      A,STATE_HOSTS
ml_ok:  ADD     A,A
        LD      E,A
        LD      D,0
        LD      HL,state_table
        ADD     HL,DE
        LD      A,(HL)
        INC     HL
        LD      H,(HL)
        LD      L,A
        JP      (HL)

state_table:
        DW      st_check_wifi
        DW      st_set_wifi
        DW      st_connect_wifi
        DW      st_hosts
        DW      st_files
        DW      st_info
        DW      st_lobby

; ---- helpers every screen shares ---------------------------------------

; status_line: type HL into message line 1.
status_line:
        LD      D,MSG_LINE1
        JP      msg_type

; status_now: HL on message line 1 at once, the sound let finish: say it
; before anything long.
status_now:
        LD      D,MSG_LINE1
        CALL    msg_put
        CALL    snd_settle
        JP      cur_steady

; legend_line: HL on message line 2.
legend_line:
        LD      D,MSG_LINE2
        JP      msg_put

; fail_code: the error buzz, HL typed on line 1 and A in hex beside it.
fail_code:
        PUSH    AF
        PUSH    HL
        LD      A,SND_ERROR
        CALL    snd_play
        POP     HL
        CALL    status_line
        POP     AF
        LD      D,MSG_LINE1
        LD      E,28
        JP      disp_hex8

; draw_frame: both windows up, the main one cleared and titled HL, the
; message lines blank.
draw_frame:
        PUSH    HL
        CALL    layout_show
        CALL    win_clear
        POP     HL
        CALL    win_title
        LD      D,MSG_LINE1
        CALL    disp_row_blank
        LD      D,MSG_LINE2
        JP      disp_row_blank

; list_row: D = the screen row of list row A. Preserves BC, E, HL.
list_row:
        ADD     A,A
        ADD     A,LIST_TOP
        LD      D,A
        RET

; list_select: the pointer onto list row A (cur_show), or with A = 0FFH
; off the current one.
list_select:
        CP      0FFH
        JP      Z,cur_hide
        CALL    list_row
        LD      E,0
        LD      B,T_CURSOR
        LD      C,T_LEFT
        JP      cur_show

; select_cur: the pointer onto row `cur`.
select_cur:
        LD      A,(cur)
        JR      list_select

; bar_move: the cursor of a one-page list (hosts) up (A = 0FFH) or down
; (A = 1), wrapping.
bar_move:
        LD      B,A
        LD      A,(nrows)
        CP      2
        RET     C
        LD      C,A
        LD      A,(cur)
        INC     B
        JR      NZ,bm_down
        OR      A
        JR      NZ,bm_dec
        LD      A,C
bm_dec: DEC     A
        JR      bm_set
bm_down:
        INC     A
        CP      C
        JR      C,bm_set
        XOR     A
bm_set: PUSH    AF
        CALL    cur_hide
        POP     AF
        LD      (cur),A
        CALL    select_cur
        LD      A,SND_MOVE
        JP      snd_play

; menu_pick: a COMMAND pop-up at the top right of the main window. HL =
; a table of B string pointers, DE = the events they stand for. Up and
; down wrap, fire picks, the right button or * cancels. Returns A = the
; picked item's event, or EV_NONE. The list's pointer stays lit beneath.
menu_pick:
        LD      (mn_names),HL
        LD      (mn_events),DE
        LD      A,B
        LD      (mn_count),A
        LD      C,0                     ; C = the widest item
mp_width:
        PUSH    BC
        LD      E,(HL)
        INC     HL
        LD      D,(HL)
        INC     HL
        PUSH    HL
        EX      DE,HL
        CALL    str_len
        POP     HL
        LD      A,B
        POP     BC
        CP      C
        JR      C,mp_wnext
        LD      C,A
mp_wnext:
        DJNZ    mp_width
        LD      A,TEXT_R-2
        SUB     C
        LD      (mn_x0),A
        LD      A,SND_OK
        CALL    snd_play
        LD      A,(mn_count)            ; the box: rows 1 to 1+2n
        ADD     A,A
        INC     A
        LD      B,A
        LD      D,1
        LD      A,(mn_x0)
        LD      E,A
        LD      C,TEXT_R-1
        CALL    ovl_open
        LD      HL,(mn_names)           ; the items
        LD      A,(mn_count)
        LD      B,A
        LD      D,2
mp_draw:
        PUSH    BC
        PUSH    DE
        LD      E,(HL)
        INC     HL
        LD      A,(HL)
        INC     HL
        PUSH    HL
        LD      H,A
        LD      L,E
        LD      A,(mn_x0)
        INC     A
        LD      E,A
        CALL    disp_str
        POP     HL
        POP     DE
        INC     D
        INC     D
        POP     BC
        DJNZ    mp_draw
        XOR     A
        LD      (in_rpt),A
        LD      (mn_index),A
        JR      mp_show
mp_moved:
        CALL    cur_hide
mp_show:
        LD      A,(mn_index)
        CALL    list_row
        LD      A,(mn_x0)
        LD      E,A
        LD      B,T_CURSOR
        LD      C,T_LEFT
        CALL    cur_show
mp_loop:
        CALL    in_read
        CP      EV_UP
        JR      Z,mp_up
        CP      EV_DOWN
        JR      Z,mp_down
        CP      EV_FIRE
        JR      Z,mp_done
        CP      EV_BACK
        JR      Z,mp_done
        CP      EV_MENU
        JR      NZ,mp_loop
mp_done:
        PUSH    AF
        LD      A,1
        LD      (in_rpt),A
        POP     AF
        PUSH    AF
        CP      EV_FIRE
        LD      A,SND_OK
        JR      Z,mp_snd
        LD      A,SND_BACK
mp_snd: CALL    snd_play
        CALL    ovl_close
        LD      A,(nrows)
        OR      A
        CALL    NZ,select_cur
        POP     AF
        CP      EV_FIRE
        LD      A,EV_NONE
        RET     NZ
        LD      HL,(mn_events)
        LD      A,(mn_index)
        LD      E,A
        LD      D,0
        ADD     HL,DE
        LD      A,(HL)
        RET
mp_up:  LD      A,(mn_index)
        OR      A
        JR      NZ,mp_up1
        LD      A,(mn_count)
mp_up1: DEC     A
        JR      mp_move
mp_down:
        LD      A,(mn_count)
        LD      B,A
        LD      A,(mn_index)
        INC     A
        CP      B
        JR      C,mp_move
        XOR     A
mp_move:
        LD      (mn_index),A
        LD      A,SND_MOVE
        CALL    snd_play
        JR      mp_moved

; ---- small string helpers ----------------------------------------------

; str_len: B = the length of the string at HL (at most 255). Preserves
; C, DE and HL.
str_len:
        PUSH    HL
        LD      B,0
sl_loop:
        LD      A,(HL)
        OR      A
        JR      Z,sl_done
        INC     HL
        INC     B
        JR      NZ,sl_loop
        DEC     B
sl_done:
        POP     HL
        RET

; str_copy: the string at HL, NUL and all, to DE. Leaves DE on its NUL.
str_copy:
        LD      A,(HL)
        LD      (DE),A
        OR      A
        RET     Z
        INC     HL
        INC     DE
        JR      str_copy

; str_end: HL onto the NUL of the string at HL. Preserves BC and DE.
str_end:
        LD      A,(HL)
        OR      A
        RET     Z
        INC     HL
        JR      str_end

; name_len: B = the length of the name at HL, stopping at a NUL or at C
; characters, whichever is first. For reading names out of the reply
; window. Preserves C, DE and HL.
name_len:
        PUSH    HL
        LD      B,0
nl_loop:
        LD      A,B
        CP      C
        JR      NC,nl_done
        LD      A,(HL)
        OR      A
        JR      Z,nl_done
        INC     HL
        INC     B
        JR      nl_loop
nl_done:
        POP     HL
        RET

