#!/usr/bin/env python3
"""mkfont.py -- turn font.txt into the Graphics I patterns CONFIG loads.

    mkfont.py font.txt build/font.inc

Emits FONT_PATTERNS, tiles 00H-7FH at 8 bytes each, and SPRITE_PATTERNS.
font.txt is shared in form with the Master System CONFIG, whose VDP flips
tiles; the TMS9918 cannot, so the flipped corners, edges and bar cap are made
here. Tile numbers (disp.inc's T_* equates must match):

    01-04  window corners: top left, top right, bottom left, bottom right
    05-06  top and bottom edge      07-08  left and right edge
    09     the pointer              0A-0B  bar caps, left and right
    0C-14  bar cells, 0-8 px filled 18     the splash triangle (own colour)
    20-7F  the font, tile = ASCII
"""

import sys

# font.txt tile -> (tile here, hflip, vflip)
PLACE = {
    0x01: [(0x01, 0, 0), (0x02, 1, 0), (0x03, 0, 1), (0x04, 1, 1)],
    0x02: [(0x05, 0, 0), (0x06, 0, 1)],
    0x03: [(0x07, 0, 0), (0x08, 1, 0)],
    0x04: [(0x09, 0, 0)],
    0x05: [(0x18, 0, 0)],
    0x08: [(0x0A, 0, 0), (0x0B, 1, 0)],
}
for n in range(9):
    PLACE[0x09 + n] = [(0x0C + n, 0, 0)]
SPRITE_SRC = 0x06


def parse(path):
    tiles = {}
    cur = None
    for lineno, raw in enumerate(open(path, encoding="ascii"), 1):
        line = raw.rstrip("\n")
        if line == "" or line == "#" or line.startswith("# "):
            cur = None
            continue
        if line.startswith("= "):
            name = line[2:3] if len(line) == 3 else line[2:].split()[0]
            code = ord(name) if len(name) == 1 else int(name[1:], 16)
            if code in tiles:
                sys.exit(f"{path}:{lineno}: tile ${code:02X} repeated")
            cur = tiles[code] = []
            continue
        if cur is None or len(line) != 8 or set(line) - set("#.") or len(cur) == 8:
            sys.exit(f"{path}:{lineno}: bad glyph row {line!r}")
        cur.append(line)
    return tiles


def rows(lines, hflip=0, vflip=0):
    lines = lines + ["........"] * (8 - len(lines))
    if vflip:
        lines = lines[::-1]
    out = []
    for line in lines:
        if hflip:
            line = line[::-1]
        out.append(sum(1 << (7 - x) for x, c in enumerate(line) if c == "#"))
    return out


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    tiles = parse(argv[1])
    pats = [[0] * 8 for _ in range(128)]
    for src, places in PLACE.items():
        for dst, hf, vf in places:
            pats[dst] = rows(tiles.get(src, []), hf, vf)
    for code in range(0x20, 0x80):
        if code in tiles:
            pats[code] = rows(tiles[code])
    with open(argv[2], "w", encoding="ascii") as f:
        f.write("; GENERATED by tools/mkfont.py from font.txt -- do not edit.\n\n")
        f.write("FONT_PATTERNS:\n")
        for code, p in enumerate(pats):
            f.write("        DB      %s\t; %02XH\n" % (",".join("%03XH" % b for b in p), code))
        f.write("\nSPRITE_PATTERNS:\n")
        f.write("        DB      %s\n" % ",".join("%03XH" % b for b in rows(tiles[SPRITE_SRC])))


if __name__ == "__main__":
    main(sys.argv)
